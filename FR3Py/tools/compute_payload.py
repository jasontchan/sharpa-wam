#!/usr/bin/env python3
"""
Compute the mass, COM and inertia of everything distal to the FR3 flange.
"""

import argparse
import sys

import mujoco
import numpy as np

from FR3Py.sim.sharpa_constants import DEFAULT_GRASP_POSE, JOINT_NAMES, JOINT_ORDER
from FR3Py.sim.sharpa_spec import (
    FLANGE_BODY,
    NUM_ARM_ACTUATORS,
    build_fr3_sharpa_spec,
    load_mount_frame,
)

Q0 = np.array(
    [0.0, -0.785398163, 0.0, -2.35619449, 0.0, 1.57079632679, 0.785398163397]
)

POSES = ("open", "grasp")

SYMMETRY_TOL = 1e-12


def pose_vector(name):
    if name == "open":
        return np.zeros(len(JOINT_ORDER), dtype=np.float64)
    return np.array([DEFAULT_GRASP_POSE[j] for j in JOINT_ORDER], dtype=np.float64)


def body_name(model, body_id):
    return mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_BODY, int(body_id))


def distal_body_ids(model, root_name):
    root = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, root_name)
    assert root >= 0, f"Body {root_name} is missing from the merged model"
    ids = {root}
    for i in range(model.nbody):
        if i != root and model.body_parentid[i] in ids:
            ids.add(i)
    return sorted(ids - {root})


def set_state(model, data, pose):
    data.qpos[:] = model.qpos0
    data.qvel[:] = 0.0
    data.qpos[:NUM_ARM_ACTUATORS] = Q0
    for name, value in zip(JOINT_NAMES, pose):
        jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, name)
        assert jid >= 0, f"Hand joint {name} is missing from the merged model"
        if model.jnt_limited[jid]:
            low, high = model.jnt_range[jid]
            value = float(np.clip(value, low, high))
        data.qpos[model.jnt_qposadr[jid]] = value
    mujoco.mj_forward(model, data)


def flange_frame(model, data, flange_to_mount):
    fid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, FLANGE_BODY)
    assert fid >= 0, f"Body {FLANGE_BODY} is missing from the merged model"

    pos_link7 = data.xpos[fid].copy()
    rot_link7 = data.xmat[fid].reshape(3, 3).copy()

    offset = np.asarray(flange_to_mount[0], dtype=np.float64)
    quat = np.asarray(flange_to_mount[1], dtype=np.float64)
    quat = quat / np.linalg.norm(quat)
    rot_offset = np.zeros(9)
    mujoco.mju_quat2Mat(rot_offset, quat)
    rot_offset = rot_offset.reshape(3, 3)

    return pos_link7 + rot_link7 @ offset, rot_link7 @ rot_offset


def payload(model, data, body_ids, origin, rotation):
    mass = 0.0
    weighted = np.zeros(3)
    positions = {}
    inertias = {}

    for i in body_ids:
        m = float(model.body_mass[i])
        r = rotation.T @ (data.xipos[i] - origin)
        principal = rotation.T @ data.ximat[i].reshape(3, 3)
        inertia = principal @ np.diag(model.body_inertia[i]) @ principal.T

        mass += m
        weighted += m * r
        positions[i] = r
        inertias[i] = inertia

    assert mass > 0.0, "Distal payload has zero mass"
    com = weighted / mass

    total = np.zeros((3, 3))
    for i in body_ids:
        m = float(model.body_mass[i])
        d = positions[i] - com
        total += inertias[i] + m * (float(d @ d) * np.eye(3) - np.outer(d, d))

    return mass, com, total


def evaluate(model, data, body_ids, flange_to_mount, pose):
    set_state(model, data, pose)
    origin, rotation = flange_frame(model, data, flange_to_mount)
    return payload(model, data, body_ids, origin, rotation)


def check(inertia):
    asymmetry = float(np.max(np.abs(inertia - inertia.T)))
    assert asymmetry <= SYMMETRY_TOL, (
        f"Inertia tensor is not symmetric to {SYMMETRY_TOL:g}: "
        f"max |I - I^T| = {asymmetry:g}"
    )
    eigenvalues = np.linalg.eigvalsh(inertia)
    assert eigenvalues[0] > 0.0, (
        f"Inertia tensor is not positive definite: eigenvalues = "
        f"{np.array2string(eigenvalues, precision=9)}"
    )
    return asymmetry, eigenvalues


def emit_yaml(path, mass, com, inertia, pose_name, count):
    values = [f"{v: .9e}" for v in inertia.reshape(9)]
    rows = [",".join(values[i : i + 3]) for i in range(0, 9, 3)]
    text = (
        "# Sharpa hand payload, expressed in the FR3 flange frame.\n"
        "#\n"
        "# mass:    kg\n"
        "# com:     [x, y, z] in metres, flange frame\n"
        "# inertia: 3x3 row-major, kg*m^2, about the COM\n"
        "#\n"
        "# Generated by tools/compute_payload.py from the merged MuJoCo model:\n"
        f"# {count} bodies distal to {FLANGE_BODY}, hand at the '{pose_name}' pose.\n"
        "\n"
        f"mass: {mass:.9f}\n"
        "\n"
        f"com: [{com[0]:.9f}, {com[1]:.9f}, {com[2]:.9f}]\n"
        "\n"
        f"inertia: [{rows[0]},\n"
        f"          {rows[1]},\n"
        f"          {rows[2]}]\n"
    )
    with open(path, "w") as f:
        f.write(text)
    return text


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Compute the flange-frame payload of the Sharpa mount and hand "
            "from the merged FR3 + Sharpa Wave model."
        )
    )
    parser.add_argument("--pose", choices=POSES, default="open")
    parser.add_argument("--emit-yaml", metavar="PATH", default=None)
    args = parser.parse_args()

    flange_to_mount, _ = load_mount_frame()
    model = build_fr3_sharpa_spec().compile()
    data = mujoco.MjData(model)

    body_ids = distal_body_ids(model, FLANGE_BODY)
    names = [body_name(model, i) for i in body_ids]

    mass, com, inertia = evaluate(
        model, data, body_ids, flange_to_mount, pose_vector(args.pose)
    )
    asymmetry, eigenvalues = check(inertia)

    print(f"Bodies distal to {FLANGE_BODY}: {len(body_ids)}")
    for name, i in zip(names, body_ids):
        print(f"  {name:34s} mass = {model.body_mass[i]: .6f} kg")
    print()

    print(f"Arm at q0 = {np.array2string(Q0, precision=4)}")
    print(f"Hand pose: {args.pose}")
    print()

    print(f"mass = {mass:.9f} kg")
    print(f"com  = [{com[0]: .9f}, {com[1]: .9f}, {com[2]: .9f}] m (flange frame)")
    print("inertia about the COM, flange frame (kg*m^2):")
    for row in inertia:
        print(f"  [{row[0]: .9e}, {row[1]: .9e}, {row[2]: .9e}]")
    print()
    print(f"max |I - I^T| = {asymmetry:.3e} (tol {SYMMETRY_TOL:g})")
    print(f"eigenvalues   = {np.array2string(eigenvalues, precision=9)}")
    print()

    coms = {}
    for name in POSES:
        coms[name] = evaluate(
            model, data, body_ids, flange_to_mount, pose_vector(name)
        )[1]
    shift = coms["grasp"] - coms["open"]
    print("COM shift, open -> grasp (flange frame):")
    print(f"  open  = [{coms['open'][0]: .9f}, {coms['open'][1]: .9f}, {coms['open'][2]: .9f}] m")
    print(f"  grasp = [{coms['grasp'][0]: .9f}, {coms['grasp'][1]: .9f}, {coms['grasp'][2]: .9f}] m")
    print(f"  delta = [{shift[0]: .9f}, {shift[1]: .9f}, {shift[2]: .9f}] m")
    print(f"  norm  = {np.linalg.norm(shift):.9f} m")

    if args.emit_yaml is not None:
        emit_yaml(args.emit_yaml, mass, com, inertia, args.pose, len(body_ids))
        print()
        print(f"Wrote {args.emit_yaml}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
