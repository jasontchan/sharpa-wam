#!/usr/bin/env python3
"""Build an UNTRAINED stage-3-shaped checkpoint for plumbing tests only.

DexTacWAM does not release stage 2 world models or stage 3 action experts, so
there is no policy to run zero-shot. This builds the exact object stage 3
training starts from -- GE base world-model weights + random-init action
expert -- so the real deploy server (tactile_server_sharpa_dexmate.py) can load
it and the full observation -> action path can be exercised on FR3 + Sharpa.

ITS ACTIONS ARE NOISE. Never execute them on hardware.

Writes:
  fr3_integration/configs/<task>_plumbing.yaml   (released yaml, local paths)
  outputs/plumbing_untrained_<task>/step_0/{diffusion_pytorch_model.safetensors,
                                            config.json, projector.pt}
"""

import argparse
import os
import sys
from pathlib import Path

import torch
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from models.ltx_models.transformer_ltx_multiview import LTXVideoTransformer3DModel  # noqa: E402
from models.tactile_models.projector import TactileProjector  # noqa: E402
from utils.model_utils import load_checkpoints  # noqa: E402

TASK_CONFIGS = {
    "pick_place_cube": "configs/cube_place/stage3_action_expert.yaml",
    "bowl": "configs/bowl_unstack/stage3_action_expert.yaml",
    "placed_tong": "configs/tongs/stage3_action_expert.yaml",
}


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--task", default="pick_place_cube", choices=sorted(TASK_CONFIGS))
    p.add_argument("--ge-base", default="pretrained_models/genie_envisioner/GE_base_fast_v0.1.safetensors")
    p.add_argument("--tactile-encoder", default="pretrained_models/dextacwam_tactile_encoder/model.pt")
    args = p.parse_args()
    os.chdir(REPO_ROOT)

    cfg = yaml.safe_load(open(TASK_CONFIGS[args.task]))
    ckpt_dir = Path(f"outputs/plumbing_untrained_{args.task}/step_0")
    ckpt_dir.mkdir(parents=True, exist_ok=True)

    # Local paths for the released stage-1 encoder and our stand-in checkpoint.
    cfg["tactile_vae"]["model_path"] = args.tactile_encoder
    cfg["diffusion_model"]["model_path"] = str(ckpt_dir)
    cfg["output_dir"] = f"outputs/plumbing_untrained_{args.task}"
    cfg_out = Path(f"fr3_integration/configs/{args.task}_plumbing.yaml")
    cfg_out.parent.mkdir(parents=True, exist_ok=True)
    with open(cfg_out, "w") as f:
        f.write("# AUTO-GENERATED by fr3_integration/make_plumbing_ckpt.py -- UNTRAINED, plumbing only\n")
        yaml.safe_dump(cfg, f, sort_keys=False)
    print(f"[plumbing] wrote {cfg_out}")

    dm_cfg = cfg["diffusion_model"]["config"]
    model = LTXVideoTransformer3DModel(**dm_cfg)
    # strict=False + ignore_mismatched_sizes: action_* keys stay random-init
    # (as with rand_init_action), view_embed (3 views in GE vs max_view here) too.
    load_checkpoints(model, args.ge_base)
    model.save_pretrained(str(ckpt_dir), safe_serialization=True)

    proj = cfg["projector"]
    projector = TactileProjector(
        latent_dim=int(proj["latent_dim"]),
        hidden_dim=int(proj["hidden_dim"]),
        num_views=int(proj["num_views"]),
    )
    torch.save(
        {
            "projector": projector.state_dict(),
            "tactile_vae_model_path": args.tactile_encoder,
            "step": 0,
            "phase": "plumbing_untrained",
            "source_projector_ckpt": None,
            "projector_frozen": True,
        },
        ckpt_dir / "projector.pt",
    )
    print(f"[plumbing] wrote {ckpt_dir} (UNTRAINED -- actions are noise)")


if __name__ == "__main__":
    main()
