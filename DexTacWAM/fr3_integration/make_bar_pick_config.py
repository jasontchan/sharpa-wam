#!/usr/bin/env python3
"""Write the stage-3 config for the FR3 + Sharpa sim bar-pick proof of concept.

Starts from the released right-only cube_place stage-3 yaml and changes only
what this setup needs:
  * phase action_only: the world-model body is GE base (no stage-2 run on this
    embodiment) and stays frozen; only the random-init action expert trains.
  * max_view 3, so GE base's 3-row view_embed loads without a size mismatch.
  * local paths for the released tactile encoder, the sim corpus and its stats.
"""

import argparse
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DOMAIN = "fr3_sharpa_bar_pick"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--n-episodes", type=int, default=100)
    p.add_argument("--n-val", type=int, default=5)
    p.add_argument("--train-steps", type=int, default=4000)
    p.add_argument("--batch-size", type=int, default=4)
    args = p.parse_args()

    cfg = yaml.safe_load(open(REPO_ROOT / "configs/cube_place/stage3_action_expert.yaml"))
    cfg["output_dir"] = f"outputs/stage3_action_only_{DOMAIN}"
    cfg["phase"] = "action_only"
    cfg["train_mode"] = "action_only"
    cfg["tactile_vae"]["model_path"] = "pretrained_models/dextacwam_tactile_encoder/model.pt"
    cfg["diffusion_model"]["model_path"] = "pretrained_models/genie_envisioner/GE_base_fast_v0.1.safetensors"
    cfg["diffusion_model"]["config"]["max_view"] = 3
    cfg["optim"]["train_steps"] = args.train_steps
    cfg["train_steps"] = args.train_steps
    cfg["steps_to_save"] = 1000
    cfg["steps_to_val"] = 1000000  # skip in-loop validation; we evaluate closed-loop in sim
    cfg["lr_warmup_steps"] = 200
    cfg["batch_size"] = args.batch_size
    cfg["dataloader_num_workers"] = 6

    n_train = args.n_episodes - args.n_val
    split = {
        "data_roots": [f"data/datasets_lerobot/{DOMAIN}"],
        "domains": [DOMAIN],
        "stat_file": f"fr3_integration/configs/{DOMAIN}_relative_stats.json",
        "cache_dir": None,
    }
    for name, eps in (("train", list(range(n_train))),
                      ("val", list(range(n_train, args.n_episodes)))):
        cfg["data"][name].update(split, episodes=eps)
    cfg["data"]["val_splits"] = {f"{DOMAIN}_val": dict(cfg["data"]["val"])}

    out = REPO_ROOT / f"fr3_integration/configs/{DOMAIN}_stage3.yaml"
    with open(out, "w") as f:
        f.write("# AUTO-GENERATED by fr3_integration/make_bar_pick_config.py\n")
        yaml.safe_dump(cfg, f, sort_keys=False)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
